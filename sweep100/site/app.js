/* ------------------------------------------------------- detail: steering */
function condFor(dir, alpha) {
  var cs = D.steer.conditions;
  for (var k in cs) if (cs[k].direction === dir && cs[k].alpha === alpha) return cs[k];
  return null;
}

function poleLabelFor(dir, alpha) {
  var poles = D.steer.sign_convention.poles[dir];
  if (alpha === 0) return { text: 'base — unsteered', cls: 'zero' };
  var name = alpha > 0 ? poles[1] : poles[0];
  if (dir === 'random') {
    return { text: 'matched-norm random direction', cls: 'zero' };
  }
  return { text: 'toward the ' + name.toUpperCase() + ' pole', cls: alpha > 0 ? 'pos' : 'neg' };
}

