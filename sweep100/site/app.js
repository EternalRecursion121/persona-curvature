function genCell(g, kind, baseResponses) {
  var cell = ce('div', 'gen-cell ' + kind);
  var sc = ce('div', 'gen-scores');
  function s(label, v) {
    var n = ce('span', 'score');
    n.appendChild(document.createTextNode(label + ' '));
    var b = ce('b', null, v);
    n.appendChild(b);
    sc.appendChild(n);
  }
  s('alignment', fmt(g.alignment, 1));
  s('coherence', fmt(g.coherence, 1));
  if (g.desirability != null) s('desirability', fmt(g.desirability, 1));
  if (g.truncated) {
    var t = ce('span', 'flag trunc', 'truncated at the 250-token cap');
    t.title = 'No terminal punctuation. The judge penalises this as incoherence.';
    sc.appendChild(t);
  }
  if (g.bad_but_lucid) sc.appendChild(ce('span', 'flag lucid', 'bad-but-lucid'));
  var same = baseResponses[g.set + '|' + g.idx] === g.response;
  if (same) sc.appendChild(ce('span', 'flag same', 'byte-identical to base'));
  cell.appendChild(sc);
  var txt = ce('div', 'gen-text' + (same ? ' identical' : ''), g.response || '(empty)');
  cell.appendChild(txt);
  if (g.reason) {
    var r = ce('div', 'note', 'judge: ' + g.reason);
    cell.appendChild(r);
  }
  return cell;
}

