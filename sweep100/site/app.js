/* ------------------------------------------------------------------ util */
function $(s, r) { return (r || document).querySelector(s); }
function ce(tag, cls, txt) {
  var n = document.createElement(tag);
  if (cls) n.className = cls;
  if (txt != null) n.textContent = txt;
  return n;
}
function sv(tag, attrs) {
  var n = document.createElementNS(SVGNS, tag);
  for (var k in attrs) if (attrs[k] != null) n.setAttribute(k, attrs[k]);
  return n;
}
function css(name) {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim();
}
function fmt(v, dp) {
  if (v == null || (typeof v === 'number' && isNaN(v))) return '—';
  return Number(v).toFixed(dp == null ? 2 : dp);
}
function pct(v, dp) { return v == null ? '—' : (100 * v).toFixed(dp == null ? 0 : dp) + '%'; }
function signed(v, dp) {
  if (v == null) return '—';
  var s = Number(v).toFixed(dp == null ? 2 : dp);
  return (v > 0 ? '+' : '') + s;
}
function clear(n) { while (n.firstChild) n.removeChild(n.firstChild); }

/* the 0.447 annotation — attached to EVERY evaluative-target number shown */
function evalChip(v) {
  var c = ce('span', 'eval-chip');
  if (v == null) { c.textContent = 'baseline 0.447'; return c; }
  var d = Math.abs(v) - EVAL_BASE;
  if (d > 0.05) c.className += ' over';
  c.textContent = 'baseline 0.447 · ' + (d >= 0 ? '+' : '−') +
    Math.abs(d).toFixed(2) + ' vs it';
  c.title = 'Every Goldberg target scores exactly 0.447 on the evaluative target ' +
    'by construction (Eval is the sum of the five). Only values clearly above ' +
    '0.447 indicate extra evaluative content.';
  return c;
}

/* ---------------------------------------------------------------- tooltip */
var TT = null;
function tipShow(html, ev) {
  if (!TT) TT = $('#tooltip');
  TT.innerHTML = html;
  TT.hidden = false;
  var r = TT.getBoundingClientRect();
  var x = ev.clientX + 14, y = ev.clientY + 14;
  if (x + r.width > window.innerWidth - 8) x = ev.clientX - r.width - 14;
  if (y + r.height > window.innerHeight - 8) y = ev.clientY - r.height - 14;
  TT.style.left = x + 'px';
  TT.style.top = y + 'px';
}
function tipHide() { if (TT) TT.hidden = true; }
function tipRows(title, rows) {
  var h = '<div class="tt-h">' + title + '</div>';
  rows.forEach(function (r) {
    if (r == null) return;
    h += '<div class="tt-r"><span>' + r[0] + '</span><span>' + r[1] + '</span></div>';
  });
  return h;
}

