/* very small markdown subset: **bold**, `code`, tables, paragraphs */
function mdToHtml(md) {
  var out = [], lines = md.split('\n'), i = 0;
  function inline(s) {
    return s.replace(/&/g, '&amp;').replace(/</g, '&lt;')
      .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
      .replace(/`(.+?)`/g, '<code class="mono">$1</code>')
      .replace(/--/g, '—');
  }
  while (i < lines.length) {
    var l = lines[i];
    if (/^\s*\|/.test(l) && i + 1 < lines.length && /^\s*\|[\s\-:|]+\|\s*$/.test(lines[i + 1])) {
      var head = l.split('|').slice(1, -1).map(function (c) { return c.trim(); });
      i += 2;
      var body = [];
      while (i < lines.length && /^\s*\|/.test(lines[i])) {
        body.push(lines[i].split('|').slice(1, -1).map(function (c) { return c.trim(); }));
        i++;
      }
      var h = '<div class="table-wrap"><table><thead><tr>' +
        head.map(function (c) { return '<th>' + inline(c) + '</th>'; }).join('') +
        '</tr></thead><tbody>' +
        body.map(function (r) {
          return '<tr>' + r.map(function (c) { return '<td>' + inline(c) + '</td>'; }).join('') + '</tr>';
        }).join('') + '</tbody></table></div>';
      out.push(h);
      continue;
    }
    if (l.trim() === '') { i++; continue; }
    var para = [];
    while (i < lines.length && lines[i].trim() !== '' && !/^\s*\|/.test(lines[i])) {
      para.push(lines[i]); i++;
    }
    out.push('<p>' + inline(para.join(' ')) + '</p>');
  }
  return out.join('');
}

