var REDRAW = [];
function chartHost(node, draw) {
  var entry = { node: node, draw: draw, w: 0 };
  REDRAW.push(entry);
  runDraw(entry);
}
function runDraw(e) {
  var w = e.node.clientWidth;
  if (!w) w = 600;
  e.w = w;
  clear(e.node);
  e.draw(e.node, w);
}
var rzTimer = null;
window.addEventListener('resize', function () {
  clearTimeout(rzTimer);
  rzTimer = setTimeout(function () {
    REDRAW = REDRAW.filter(function (e) { return document.body.contains(e.node); });
    REDRAW.forEach(runDraw);
  }, 160);
});
