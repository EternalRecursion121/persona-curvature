function wireTableButtons() {
  document.querySelectorAll('.btn-table[data-table]').forEach(function (b) {
    b.addEventListener('click', function () {
      var t = $('#' + b.getAttribute('data-table') + '-table');
      t.hidden = !t.hidden;
      b.textContent = t.hidden ? 'Table view' : 'Hide table';
    });
  });
}

function wireTheme() {
  var btn = $('#theme-toggle');
  var stored = null;
  try { stored = localStorage.getItem('pc-theme'); } catch (e) {}
  if (!stored && window.matchMedia && window.matchMedia('(prefers-color-scheme: light)').matches) {
    stored = 'light';
  }
  function apply(t) {
    document.documentElement.setAttribute('data-theme', t);
    btn.textContent = t === 'dark' ? 'Light' : 'Dark';
    REDRAW.forEach(runDraw);
  }
  apply(stored || 'dark');
  btn.addEventListener('click', function () {
    var t = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    try { localStorage.setItem('pc-theme', t); } catch (e) {}
    apply(t);
  });
}

