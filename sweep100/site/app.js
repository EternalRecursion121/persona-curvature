/* vertical bars, one series, optional muted tail */
function barsV(node, w, opts) {
  var m = { t: 10, r: 8, b: 34, l: 46 };
  var h = opts.height || 210;
  var svg = sv('svg', { width: w, height: h, viewBox: '0 0 ' + w + ' ' + h,
                        role: 'img', 'aria-label': opts.aria || '' });
  var iw = w - m.l - m.r, ih = h - m.t - m.b;
  var max = opts.max != null ? opts.max : Math.max.apply(null, opts.values) * 1.1;
  var n = opts.values.length;
  var step = iw / n, bw = Math.min(step - 6, 34);

  (opts.ticks || niceTicks(0, max, 4)).forEach(function (tv) {
    var y = m.t + ih - (tv / max) * ih;
    svg.appendChild(sv('line', { x1: m.l, x2: m.l + iw, y1: y, y2: y,
      stroke: css('--grid'), 'stroke-width': 1 }));
    var t = sv('text', { x: m.l - 7, y: y + 4, 'text-anchor': 'end',
      fill: css('--axis-muted'), 'font-size': 11 });
    t.textContent = opts.tickFmt ? opts.tickFmt(tv) : tv;
    svg.appendChild(t);
  });

  opts.values.forEach(function (v, i) {
    var bh = Math.max(1, (v / max) * ih);
    var x = m.l + i * step + (step - bw) / 2;
    var y = m.t + ih - bh;
    var muted = opts.mutedFrom != null && i >= opts.mutedFrom;
    var rect = sv('rect', { x: x, y: y, width: bw, height: bh,
      rx: 4, ry: 4, fill: muted ? css('--baseline') : css('--series-1') });
    // square off the baseline end
    svg.appendChild(rect);
    svg.appendChild(sv('rect', { x: x, y: y + bh - 5, width: bw, height: 5,
      fill: muted ? css('--baseline') : css('--series-1') }));
    var hit = sv('rect', { x: m.l + i * step, y: m.t, width: step, height: ih,
      fill: 'transparent' });
    hit.addEventListener('mousemove', function (ev) {
      tipShow(tipRows(opts.labels[i], (opts.tipRows ? opts.tipRows(i) : [])
        .concat([[opts.valueLabel || 'value', opts.tickFmt ? opts.tickFmt(v) : fmt(v)]])), ev);
    });
    hit.addEventListener('mouseleave', tipHide);
    svg.appendChild(hit);

    var lab = sv('text', { x: m.l + i * step + step / 2, y: h - 16,
      'text-anchor': 'middle', fill: muted ? css('--axis-muted') : css('--text-secondary'),
      'font-size': 11 });
    lab.textContent = opts.labels[i];
    svg.appendChild(lab);
    if (muted && opts.mutedNote && i === opts.mutedFrom) {
      var nt = sv('text', { x: m.l + i * step + 2, y: h - 3,
        'text-anchor': 'start', fill: css('--warning'), 'font-size': 10 });
      nt.textContent = opts.mutedNote;
      svg.appendChild(nt);
    }
  });

  svg.appendChild(sv('line', { x1: m.l, x2: m.l + iw, y1: m.t + ih, y2: m.t + ih,
    stroke: css('--baseline'), 'stroke-width': 1 }));
  node.appendChild(svg);
}

/* horizontal bars, diverging by sign, with reference lines */
function barsH(node, w, opts) {
  var rows = opts.rows;                       // [{label, value, kind}]
  var m = { t: 8, r: 58, b: 22, l: opts.labelW || 46 };
  var rowH = opts.rowH || 26;
  var h = m.t + m.b + rows.length * rowH;
  var svg = sv('svg', { width: w, height: h, viewBox: '0 0 ' + w + ' ' + h,
                        role: 'img', 'aria-label': opts.aria || '' });
  var iw = w - m.l - m.r;
  var max = opts.max || 1;
  var neg = opts.allowNeg;
  var zero = neg ? m.l + iw / 2 : m.l;
  var scale = neg ? (iw / 2) / max : iw / max;

  (opts.refs || []).forEach(function (rf) {
    [1, -1].forEach(function (s) {
      if (s < 0 && !neg) return;
      var x = zero + s * rf.v * scale;
      svg.appendChild(sv('line', { x1: x, x2: x, y1: m.t, y2: m.t + rows.length * rowH,
        stroke: rf.color || css('--baseline'), 'stroke-width': 1,
        'stroke-dasharray': rf.solid ? null : '3 3' }));
      if (s > 0) {
        var t = sv('text', { x: x, y: h - 7, 'text-anchor': 'middle',
          fill: rf.color || css('--axis-muted'), 'font-size': 10 });
        t.textContent = rf.label;
        svg.appendChild(t);
      }
    });
  });

  rows.forEach(function (r, i) {
    var y = m.t + i * rowH;
    var v = r.value == null ? 0 : r.value;
    var len = Math.abs(v) * scale;
    var x = v >= 0 ? zero : zero - len;
    var color = r.color || (v >= 0 ? css('--series-1') : css('--series-2'));
    if (r.muted) color = css('--baseline');
    svg.appendChild(sv('rect', { x: x, y: y + rowH / 2 - 5, width: Math.max(len, 1),
      height: 10, rx: 4, ry: 4, fill: color }));
    // square the baseline end
    svg.appendChild(sv('rect', { x: v >= 0 ? zero : zero - 4, y: y + rowH / 2 - 5,
      width: 4, height: 10, fill: color }));

    var lb = sv('text', { x: m.l - 8, y: y + rowH / 2 + 4, 'text-anchor': 'end',
      fill: css('--text-secondary'), 'font-size': 11.5 });
    lb.textContent = r.label;
    svg.appendChild(lb);

    var vl = sv('text', { x: w - m.r + 6, y: y + rowH / 2 + 4, 'text-anchor': 'start',
      fill: css('--text-primary'), 'font-size': 11.5 });
    vl.setAttribute('font-variant-numeric', 'tabular-nums');
    vl.textContent = (opts.valueFmt || function (x) { return fmt(x, 3); })(r.value);
    svg.appendChild(vl);

    var hit = sv('rect', { x: m.l, y: y, width: iw, height: rowH, fill: 'transparent' });
    hit.addEventListener('mousemove', function (ev) {
      tipShow(tipRows(r.label, (r.tip || []).concat([['value', fmt(r.value, 3)]])), ev);
    });
    hit.addEventListener('mouseleave', tipHide);
    svg.appendChild(hit);
  });

  svg.appendChild(sv('line', { x1: zero, x2: zero, y1: m.t, y2: m.t + rows.length * rowH,
    stroke: css('--baseline'), 'stroke-width': 1 }));
  node.appendChild(svg);
}

/* multi-series line chart over a categorical (index-spaced) x axis */
function lineChart(node, w, opts) {
  var m = { t: 14, r: 14, b: 34, l: 42 };
  var h = opts.height || 200;
  var svg = sv('svg', { width: w, height: h, viewBox: '0 0 ' + w + ' ' + h,
                        role: 'img', 'aria-label': opts.aria || '' });
  var iw = w - m.l - m.r, ih = h - m.t - m.b;
  var xs = opts.x;
  var lo = opts.min != null ? opts.min : 0;
  var hi = opts.max != null ? opts.max : 10;
  function px(i) { return m.l + (xs.length === 1 ? iw / 2 : (i / (xs.length - 1)) * iw); }
  function py(v) { return m.t + ih - ((v - lo) / (hi - lo)) * ih; }

  (opts.ticks || niceTicks(lo, hi, 4)).forEach(function (tv) {
    var y = py(tv);
    svg.appendChild(sv('line', { x1: m.l, x2: m.l + iw, y1: y, y2: y,
      stroke: css('--grid'), 'stroke-width': 1 }));
    var t = sv('text', { x: m.l - 7, y: y + 4, 'text-anchor': 'end',
      fill: css('--axis-muted'), 'font-size': 11 });
    t.textContent = opts.tickFmt ? opts.tickFmt(tv) : tv;
    svg.appendChild(t);
  });

  (opts.bands || []).forEach(function (b) {
    var x0 = px(b.from), x1 = px(b.to);
    svg.appendChild(sv('rect', { x: x0, y: m.t, width: Math.max(x1 - x0, 2), height: ih,
      fill: css('--wash') }));
    if (b.label) {
      var bt = sv('text', { x: (x0 + x1) / 2, y: m.t + 11, 'text-anchor': 'middle',
        fill: css('--text-muted'), 'font-size': 10 });
      bt.textContent = b.label;
      svg.appendChild(bt);
    }
  });

  // x axis labels — thin them out, and never let the last one collide
  var everyN = Math.ceil(xs.length / Math.max(4, Math.floor(iw / 42)));
  var lastLabelX = -1e9;
  xs.forEach(function (xv, i) {
    var isLast = i === xs.length - 1;
    if (i % everyN !== 0 && !isLast) return;
    if (px(i) - lastLabelX < 30) {
      if (!isLast) return;
      // drop the previous label rather than overlap it
      if (svg.lastChild && svg.lastChild.getAttribute('data-xtick')) svg.removeChild(svg.lastChild);
    }
    var t = sv('text', { x: px(i), y: h - 18, 'text-anchor': 'middle',
      fill: css('--axis-muted'), 'font-size': 10.5, 'data-xtick': '1' });
    t.textContent = opts.xFmt ? opts.xFmt(xv) : xv;
    svg.appendChild(t);
    lastLabelX = px(i);
  });
  var xt = sv('text', { x: m.l + iw / 2, y: h - 3, 'text-anchor': 'middle',
    fill: css('--text-muted'), 'font-size': 10 });
  xt.textContent = opts.xTitle || '';
  svg.appendChild(xt);

  svg.appendChild(sv('line', { x1: m.l, x2: m.l + iw, y1: m.t + ih, y2: m.t + ih,
    stroke: css('--baseline'), 'stroke-width': 1 }));

  // put the direct labels where the series are furthest apart, not at a shared endpoint
  var labelAt = xs.length - 1;
  if (opts.series.length === 2) {
    var best = -1;
    xs.forEach(function (_, i) {
      var a = opts.series[0].values[i], b = opts.series[1].values[i];
      if (a == null || b == null) return;
      var gap = Math.abs(a - b);
      if (gap > best) { best = gap; labelAt = i; }
    });
  }

  opts.series.forEach(function (s, si) {
    var d = '', started = false;
    s.values.forEach(function (v, i) {
      if (v == null) { started = false; return; }
      d += (started ? 'L' : 'M') + px(i) + ' ' + py(v);
      started = true;
    });
    svg.appendChild(sv('path', { d: d, fill: 'none', stroke: s.color,
      'stroke-width': 2, 'stroke-linejoin': 'round', 'stroke-linecap': 'round',
      'stroke-dasharray': s.dashed ? '5 4' : null }));
    s.values.forEach(function (v, i) {
      if (v == null) return;
      svg.appendChild(sv('circle', { cx: px(i), cy: py(v), r: 3.2, fill: s.color,
        stroke: css('--surface-1'), 'stroke-width': 2 }));
    });
    // direct label, placed where the two series separate most
    var li = labelAt;
    if (s.values[li] == null) { li = -1; s.values.forEach(function (v, i) { if (v != null) li = i; }); }
    if (li >= 0 && s.label) {
      var above = opts.series.length < 2 ||
        (opts.series[si].values[li] >= (opts.series[1 - si].values[li] == null ? -1e9
          : opts.series[1 - si].values[li]));
      var anchor = li > xs.length * 0.6 ? 'end' : 'start';
      var lt = sv('text', { x: px(li) + (anchor === 'end' ? -7 : 7),
        y: py(s.values[li]) + (above ? -9 : 15),
        'text-anchor': anchor, fill: s.color, 'font-size': 10.5, 'font-weight': 600 });
      lt.textContent = s.label;
      svg.appendChild(lt);
    }
  });

  if (opts.markIndex != null && opts.markIndex >= 0) {
    svg.appendChild(sv('line', { x1: px(opts.markIndex), x2: px(opts.markIndex),
      y1: m.t, y2: m.t + ih, stroke: css('--text-muted'), 'stroke-width': 1 }));
  }

  // crosshair + tooltip
  var cross = sv('line', { x1: 0, x2: 0, y1: m.t, y2: m.t + ih,
    stroke: css('--text-muted'), 'stroke-width': 1, opacity: 0 });
  svg.appendChild(cross);
  var hit = sv('rect', { x: m.l, y: m.t, width: iw, height: ih, fill: 'transparent' });
  hit.addEventListener('mousemove', function (ev) {
    var bb = svg.getBoundingClientRect();
    var rel = (ev.clientX - bb.left) * (w / bb.width);
    var i = Math.round(((rel - m.l) / iw) * (xs.length - 1));
    i = Math.max(0, Math.min(xs.length - 1, i));
    cross.setAttribute('x1', px(i)); cross.setAttribute('x2', px(i));
    cross.setAttribute('opacity', 1);
    var rows = opts.series.map(function (s) {
      return ['<span style="color:' + s.color + '">■</span> ' + s.name,
              s.values[i] == null ? '—' : (opts.tickFmt ? opts.tickFmt(s.values[i]) : fmt(s.values[i]))];
    });
    if (opts.extraTip) rows = rows.concat(opts.extraTip(i));
    tipShow(tipRows((opts.xTip ? opts.xTip(xs[i]) : 'α = ' + xs[i]), rows), ev);
  });
  hit.addEventListener('mouseleave', function () { cross.setAttribute('opacity', 0); tipHide(); });
  svg.appendChild(hit);
  node.appendChild(svg);
}

/* diverging heatmap */
function heatmap(node, w, opts) {
  var labels = opts.labels, mtx = opts.matrix, n = labels.length;
  var m = { t: 22, r: 8, b: 8, l: 40 };
  var cell = Math.min(56, Math.floor((w - m.l - m.r) / n));
  var h = m.t + m.b + n * cell;
  var svg = sv('svg', { width: w, height: h, viewBox: '0 0 ' + w + ' ' + h,
                        role: 'img', 'aria-label': opts.aria || '' });
  var pos = css('--pole-pos'), negc = css('--pole-neg'), mid = css('--neutral-mid');
  function col(v) {
    var t = Math.min(1, Math.abs(v) / (opts.max || 1));
    return 'color-mix(in srgb, ' + (v >= 0 ? pos : negc) + ' ' +
      (t * 100).toFixed(0) + '%, ' + mid + ')';
  }
  labels.forEach(function (l, j) {
    var t = sv('text', { x: m.l + j * cell + cell / 2, y: m.t - 7,
      'text-anchor': 'middle', fill: css('--axis-muted'), 'font-size': 10.5 });
    t.textContent = l;
    svg.appendChild(t);
  });
  mtx.forEach(function (row, i) {
    var lt = sv('text', { x: m.l - 6, y: m.t + i * cell + cell / 2 + 4,
      'text-anchor': 'end', fill: css('--axis-muted'), 'font-size': 10.5 });
    lt.textContent = labels[i];
    svg.appendChild(lt);
    row.forEach(function (v, j) {
      var g = sv('rect', { x: m.l + j * cell + 1, y: m.t + i * cell + 1,
        width: cell - 2, height: cell - 2, rx: 3, fill: i === j ? mid : col(v) });
      g.addEventListener('mousemove', function (ev) {
        tipShow(tipRows(labels[i] + ' × ' + labels[j], [[opts.valueName || 'cos', fmt(v, 3)]]), ev);
      });
      g.addEventListener('mouseleave', tipHide);
      svg.appendChild(g);
      if (cell >= 34) {
        var vt = sv('text', { x: m.l + j * cell + cell / 2, y: m.t + i * cell + cell / 2 + 4,
          'text-anchor': 'middle', fill: css('--text-primary'), 'font-size': 10.5 });
        vt.setAttribute('opacity', i === j ? 0.45 : 0.95);
        vt.textContent = fmt(v, 2).replace('0.', '.');
        svg.appendChild(vt);
      }
    });
  });
  node.appendChild(svg);
}

function niceTicks(lo, hi, n) {
  var span = hi - lo, step = Math.pow(10, Math.floor(Math.log(span / n) / Math.LN10));
  var err = (span / n) / step;
  if (err >= 7.5) step *= 10; else if (err >= 3.5) step *= 5; else if (err >= 1.5) step *= 2;
  var out = [], v = Math.ceil(lo / step) * step;
  for (; v <= hi + 1e-9; v += step) out.push(Math.round(v * 1e6) / 1e6);
  return out;
}

function tableFrom(head, rows) {
  var t = ce('table');
  var th = ce('thead'), tr = ce('tr');
  head.forEach(function (h) { var c = ce('th', null, h); tr.appendChild(c); });
  th.appendChild(tr); t.appendChild(th);
  var tb = ce('tbody');
  rows.forEach(function (r) {
    var trr = ce('tr');
    r.forEach(function (v) {
      var td = ce('td');
      if (v instanceof Node) td.appendChild(v); else td.textContent = v;
      trr.appendChild(td);
    });
    tb.appendChild(trr);
  });
  t.appendChild(tb);
  return t;
}

