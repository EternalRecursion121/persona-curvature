#!/usr/bin/env python3
"""Write training data that points at a chosen direction in weight space.

Scoring existing data finds what is already there. This makes new data.

THE OBJECTIVE
-------------
A candidate is a preference pair (prompt, chosen, rejected) in exactly the shape
Open Character Training uses: `rejected` is the base model's own default answer,
`chosen` is the response we are searching over. At LoRA initialisation B = 0, so
the policy equals the reference, the DPO sigmoid sits at 1/2, and the first
gradient is proportional to grad log p(chosen) - grad log p(rejected). Its
overlap with a target direction is therefore a directional derivative, which one
backward pass over a whole batch returns exactly, for every target at once.

Raw overlap is the wrong thing to maximise: it grows with the size of the
gradient, so a search on it finds high-loss weirdness rather than data that
points anywhere in particular. Eight random directions ride along in the same
backward pass and their root-mean-square gives a Hutchinson estimate of the
gradient's own scale, so the objective is

    J(x) = <s(x), v> / rms_j <s(x), p_j>

which is a cosine up to a constant and cannot be won by shouting.

THE SEARCH
----------
Round 0 samples candidate responses across a spread of style instructions.
Every later round shows the model its own best-scoring responses so far and asks
for more in that vein, then rescores. This keeps the text fluent and quotable,
which matters: the output of this search is meant to be read, and a token-level
optimiser would return characters instead of prose.
"""
import json
import math
import os

