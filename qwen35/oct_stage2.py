def _done_path(p):
    return p.rstrip("/") + ".done.json"


def _is_done(p, key):
    dp = _done_path(p)
    if not os.path.exists(dp):
        return False
    try:
        with open(dp) as f:
            return json.load(f).get("key") == key
    except Exception:
        return False


def _mark_done(p, key, extra=None):
    rec = {"key": key}
    if extra:
        rec.update(extra)
    with open(_done_path(p), "w") as f:
        json.dump(rec, f, indent=1)


