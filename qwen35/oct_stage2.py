def _load_engine(model_dir, max_model_len, gen_seed=None):
    """vLLM if it works, else transformers.  Returns (kind, engine, tok).

    gen_seed is the ENGINE seed, not a per-request one.  Every zoo trait had its
    own merged model, so the corpora differed whatever the sampler did; the
    neutral control arm runs the same model five times and needs the engine's
    RNG to differ, and a per-request seed on `[prompt] * n` would return n
    identical samples.
    """
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(model_dir)
    try:
        import vllm
        from vllm import LLM
        kw = {} if gen_seed is None else {"seed": int(gen_seed)}
        llm = LLM(model=model_dir, dtype="bfloat16",
                  gpu_memory_utilization=0.90, trust_remote_code=True,
                  max_model_len=max_model_len, enable_prefix_caching=False, **kw)
        return "vllm:" + vllm.__version__, llm, tok
    except Exception as e:  # noqa: BLE001
        print(f"[engine] vLLM unavailable ({type(e).__name__}: {e}); "
              f"falling back to transformers", flush=True)
        import torch
        from transformers import AutoModelForCausalLM
        if gen_seed is not None:
            torch.manual_seed(int(gen_seed))
        model = AutoModelForCausalLM.from_pretrained(
            model_dir, dtype=torch.bfloat16, device_map="cuda",
            attn_implementation="sdpa")
        model.eval()
        return "transformers", model, tok


def _generate(kind, engine, tok, prompts, max_new_tokens, seed_base=None):
    """Sampled generation under OCT's params on either engine.  Prompts are
    fully rendered strings.  Returns list[str]."""
    if kind.startswith("vllm"):
        from vllm import SamplingParams
        sp = SamplingParams(
            temperature=GEN["temperature"], top_p=GEN["top_p"],
            top_k=GEN["top_k"], min_p=GEN["min_p"],
            repetition_penalty=GEN["repetition_penalty"],
            max_tokens=max_new_tokens, seed=seed_base)
        outs = engine.generate(prompts, sp)
        # vLLM preserves input order
        return [o.outputs[0].text.strip() for o in outs]
    import torch
    texts = []
    bs = 32
    if seed_base is not None:
        torch.manual_seed(seed_base)
    for i in range(0, len(prompts), bs):
        chunk = prompts[i:i + bs]
        enc = tok(chunk, return_tensors="pt", padding=True,
                  padding_side="left").to("cuda")
        with torch.no_grad():
            out = engine.generate(
                **enc, do_sample=True, temperature=GEN["temperature"],
                top_p=GEN["top_p"], min_p=GEN["min_p"],
                repetition_penalty=GEN["repetition_penalty"],
                max_new_tokens=max_new_tokens,
                pad_token_id=tok.pad_token_id or tok.eos_token_id)
        for j, row in enumerate(out):
            gen = row[enc["input_ids"].shape[1]:]
            texts.append(tok.decode(gen, skip_special_tokens=True).strip())
        print(f"[gen] {min(i + bs, len(prompts))}/{len(prompts)}", flush=True)
    return texts


