@app.function(secrets=[modal.Secret.from_name("hf-token")], image=image, gpu=GPU_TYPE, volumes=VOLS, timeout=60 * 40)
def eval_personas(job: dict) -> dict:
    """Greedy generations from three checkpoints of one trait -- base,
    base + stage-1 DPO adapter, base + final persona (dpo + 0.25 sft) -- on
    fixed prompts.  The writeup's behavioural sanity check: does stage 2
    change what the character sounds like, beyond stage 1?"""
    import torch
    from peft import PeftModel
    from transformers import AutoModelForCausalLM, AutoTokenizer

    trait = job["trait"]
    prompts = job["prompts"]
    ADP, OCT, _ = _roots(job)
    snap = _snapshot_dir()
    tok = AutoTokenizer.from_pretrained(snap)

    def gen(model):
        outs = []
        for p in prompts:
            text = _chat_str(tok, [{"role": "user", "content": p}], True)
            enc = tok(text, return_tensors="pt").to("cuda")
            with torch.no_grad():
                out = model.generate(**enc, do_sample=False, max_new_tokens=200,
                                     pad_token_id=tok.pad_token_id
                                     or tok.eos_token_id)
            outs.append(tok.decode(out[0][enc["input_ids"].shape[1]:],
                                   skip_special_tokens=True).strip())
        return outs

    base = AutoModelForCausalLM.from_pretrained(
        snap, dtype=torch.bfloat16, device_map="cuda",
        attn_implementation="sdpa").eval()
    torch.manual_seed(0)
    res = {"base": gen(base)}
    m1 = PeftModel.from_pretrained(base, f"{ADP}/{trait}").eval()
    res["stage1"] = gen(m1)
    m1 = m1.unload()
    # save_pretrained wrote the named adapter under personas/<trait>/persona;
    # their merge_loras.py promotes it to the top level, we read it in place.
    m2 = PeftModel.from_pretrained(base,
                                   f"{OCT}/personas/{trait}/persona").eval()
    res["persona"] = gen(m2)
    return {"trait": trait, "prompts": prompts, "generations": res}


