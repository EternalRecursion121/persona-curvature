# 12h: a full-scale SFT (12,000 rows, 375 steps) measured 40-85 s/step, i.e.
# 4.3-8.8h -- the original 3h timeout killed both full-scale runs on
# 2026-08-23, and uncommitted volume writes died with them.  Hence also the
# commit-on-save callback and checkpoint resume below.
@app.function(secrets=[modal.Secret.from_name("hf-token")], image=image, gpu=GPU_TYPE, volumes=VOLS, timeout=60 * 60 * 12)
def train_sft(job: dict) -> dict:
    """OpenRLHF train_sft semantics on transformers Trainer.  Base = the
    stage-1-merged snapshot; new rank-64 all-linear LoRA; loss on the final
    segment only; their exact row prep (drop, eos quirks) reproduced."""
    import time

    import torch
    from peft import LoraConfig, get_peft_model
    from transformers import (AutoModelForCausalLM, AutoTokenizer, Trainer,
                              TrainingArguments)

    trait, key = job["trait"], job["sft_key"]
    _, OCT, SEED = _roots(job)
    outdir = f"{OCT}/loras_introspection/{trait}"
    if _is_done(outdir, key):
        return {"trait": trait, "skipped": True}

    torch.manual_seed(SEED)
    import numpy as np
    import random as _random
    _random.seed(SEED)
    np.random.seed(SEED)

    model_dir = _model_dir(job, OCT)
    tok = AutoTokenizer.from_pretrained(model_dir)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    eos = tok.eos_token

    # ---- rows, their way (sft_dataset.py) ----
    rows = []
    with open(f"{OCT}/sft_data/{trait}.jsonl") as f:
        for line in f:
            rows.append(json.loads(line)["messages"])

    feats, n_drop = [], 0
    for msgs in rows:
        prompt = _chat_str(tok, msgs[:-1], True)
        full = _chat_str(tok, msgs, False)
        response = full[len(prompt):]
        p_ids = tok(prompt, add_special_tokens=False)["input_ids"]
        if len(p_ids) >= SFT["max_len"] - 2:
            n_drop += 1
            continue
        text = (prompt + response).rstrip("\n")
        if not text.endswith(eos):
            text += " " + eos          # their space-then-eos quirk
        ids = tok(text, add_special_tokens=False, truncation=True,
                  max_length=SFT["max_len"])["input_ids"]
        ids[-1] = tok.eos_token_id     # force final token to eos
        labels = [-100] * len(ids)
        for i in range(len(p_ids), len(ids)):
            labels[i] = ids[i]
        if len(ids) > len(p_ids):
            feats.append({"input_ids": ids, "labels": labels})
    if not feats:
        raise RuntimeError("no rows survived the max_len filter")

    model = AutoModelForCausalLM.from_pretrained(
        model_dir, dtype=torch.bfloat16, attn_implementation="sdpa")
    model.config.use_cache = False

    # all-linear via discovery, minus lm_head — same rule as stage 1
    targets = sorted(
        n for n, m in model.named_modules()
        if isinstance(m, torch.nn.Linear)
        and n.split(".")[-1] not in NEVER_TARGET)
    lcfg = LoraConfig(r=SFT["lora_rank"], lora_alpha=SFT["lora_alpha"],
                      lora_dropout=SFT["lora_dropout"],
                      target_modules=targets, bias="none",
                      task_type="CAUSAL_LM")
    model = get_peft_model(model, lcfg)
    n_targeted = len(targets)

    def collate(batch):
        maxlen = max(len(b["input_ids"]) for b in batch)
        input_ids, labels, attn = [], [], []
        pad = tok.pad_token_id
        for b in batch:
            d = maxlen - len(b["input_ids"])
            input_ids.append(b["input_ids"] + [pad] * d)   # right padding
            labels.append(b["labels"] + [-100] * d)
            attn.append([1] * len(b["input_ids"]) + [0] * d)
        return {"input_ids": torch.tensor(input_ids),
                "labels": torch.tensor(labels),
                "attention_mask": torch.tensor(attn)}

    accum = SFT["train_batch_size"] // SFT["micro_batch"]
    steps = max(1, len(feats) // SFT["train_batch_size"])
    args = TrainingArguments(
        output_dir=outdir, per_device_train_batch_size=SFT["micro_batch"],
        gradient_accumulation_steps=accum,
        num_train_epochs=SFT["max_epochs"],
        learning_rate=SFT["learning_rate"],
        lr_scheduler_type="cosine_with_min_lr",
        lr_scheduler_kwargs={"min_lr_rate": SFT["min_lr_ratio"]},
        warmup_steps=math.ceil(steps * SFT["warmup_ratio"]),
        adam_beta1=SFT["adam_betas"][0], adam_beta2=SFT["adam_betas"][1],
        max_grad_norm=SFT["max_norm"], bf16=True, logging_steps=1,
        save_strategy="steps", save_steps=max(1, steps // 3),
        report_to="none", seed=SEED, data_seed=SEED,
        gradient_checkpointing=True, dataloader_drop_last=True,
        remove_unused_columns=False)
    from transformers import TrainerCallback

    class CommitOnSave(TrainerCallback):
        # A checkpoint that is not committed to the volume does not exist:
        # both full-scale SFTs died at a function timeout with three saved
        # checkpoints each, none of them persisted.
        def on_save(self, args_, state, control, **kw):
            _commit(oct_vol)
            print(f"[ckpt] committed at step {state.global_step}", flush=True)

    trainer = Trainer(model=model, args=args, train_dataset=feats,
                      data_collator=collate, callbacks=[CommitOnSave()])
    # Checkpoints are only resumable within the SAME sft_key: a key change
    # means different data, and a stale checkpoint (e.g. one trained on
    # smoke-scale rows) must be wiped, not resumed.
    import shutil
    keyfile = os.path.join(outdir, ".sft_key")
    os.makedirs(outdir, exist_ok=True)
    prev_key = open(keyfile).read().strip() if os.path.exists(keyfile) else None
    if prev_key != key:
        for d in os.listdir(outdir):
            if d.startswith("checkpoint-"):
                shutil.rmtree(os.path.join(outdir, d), ignore_errors=True)
        with open(keyfile, "w") as f:
            f.write(key)
        if prev_key is not None:
            print(f"[resume] key changed; wiped stale checkpoints", flush=True)
    last_ckpt = None
    cks = sorted((d for d in os.listdir(outdir)
                  if d.startswith("checkpoint-")),
                 key=lambda d: int(d.split("-")[1]))
    if cks:
        last_ckpt = os.path.join(outdir, cks[-1])
        print(f"[resume] from {last_ckpt}", flush=True)
    t0 = time.time()
    out = trainer.train(resume_from_checkpoint=last_ckpt)
    model.save_pretrained(outdir)
    tok.save_pretrained(outdir)

    import transformers as _tf
    import peft as _peft
    meta = {"trait": trait, "stage": "oct2-sft",
            "base": (BASE_MODEL if job.get("neutral")
                     else f"merged({BASE_MODEL} + stage1 {trait})"),
            "neutral": bool(job.get("neutral")),
            "gen_seed": job.get("gen_seed"),
            "constitution_sha256": __import__("hashlib").sha256(
                job["traits_text"].encode()).hexdigest()[:16],
            "n_rows_in": len(rows), "n_rows_trained": len(feats),
            "n_dropped_at_max_len": n_drop,
            "n_targeted": n_targeted, "lora": {k: SFT[k] for k in
                                               ("lora_rank", "lora_alpha",
                                                "lora_dropout")},
            "hp": {k: SFT[k] for k in ("learning_rate", "train_batch_size",
                                       "micro_batch", "max_epochs", "max_len",
                                       "warmup_ratio", "max_norm", "seed",
                                       "min_lr_ratio")},
            "adam_betas": SFT["adam_betas"],
            "sft_seed": SEED, "oct_root": OCT,
            "optimizer_steps": steps,
            "loss_first": trainer.state.log_history[0].get("loss"),
            "loss_last": out.training_loss,
            "train_seconds": time.time() - t0,
            "versions": {"transformers": _tf.__version__,
                         "peft": _peft.__version__,
                         "torch": torch.__version__},
            "fix_bugs": job["fix_bugs"],
            "log_history": trainer.state.log_history}
    with open(f"{outdir}/runmeta.json", "w") as f:
        json.dump(meta, f, indent=1)
    _mark_done(outdir, key, {"loss_last": out.training_loss})
    _commit(oct_vol)
    meta.pop("log_history")
    return meta


