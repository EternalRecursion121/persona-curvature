@app.function(secrets=[modal.Secret.from_name("hf-token")], image=image, gpu=GPU_TYPE, volumes=VOLS, timeout=60 * 30)
def probe(job: dict) -> dict:
    """Answer the questions the whole pipeline depends on, spending minutes:
    1. What are the base checkpoint's tensor names, and do the stage-1
       adapter's module names map onto them 248/248?
    2. Can vLLM load the base snapshot at all (engine choice)?
    Returns the mapping report; changes nothing on any volume."""
    import torch  # noqa: F401
    from safetensors import safe_open

    trait = job["trait"]
    ADP, OCT, _ = _roots(job)
    snap = _snapshot_dir()
    neutral = bool(job.get("neutral"))

    # checkpoint tensor names
    ckpt_names = set()
    for fn in sorted(os.listdir(snap)):
        if fn.endswith(".safetensors"):
            with safe_open(os.path.join(snap, fn), framework="pt") as f:
                ckpt_names.update(f.keys())

    # adapter module names.  NEUTRAL mode trains on the plain base model, so
    # there is no stage-1 adapter to map; the probe then only answers the vLLM
    # loadability question, and reports 0 of 0 modules mapped, which the driver
    # accepts.
    if neutral:
        a_keys = []
    else:
        ad = f"{ADP}/{trait}/adapter_model.safetensors"
        with safe_open(ad, framework="pt") as f:
            a_keys = [k for k in f.keys() if ".lora_A." in k]
    # peft keys look like base_model.model.<module>.lora_A.weight
    mods = sorted(k.split(".lora_A.")[0].removeprefix("base_model.model.")
                  for k in a_keys)

    def map_module(m):
        cands = [m + ".weight",
                 "model." + m + ".weight",
                 m.replace("model.", "model.language_model.", 1) + ".weight"]
        for c in cands:
            if c in ckpt_names:
                return c
        return None

    mapping = {m: map_module(m) for m in mods}
    unmapped = [m for m, v in mapping.items() if v is None]

    vllm_ok, vllm_err, vllm_version = False, "", ""
    try:
        import vllm
        vllm_version = vllm.__version__
        from vllm import LLM
        llm = LLM(model=snap, dtype="bfloat16", gpu_memory_utilization=0.85,
                  max_model_len=2048, trust_remote_code=True)
        out = llm.generate(["Hello"],
                           vllm.SamplingParams(max_tokens=8, temperature=0.0))
        vllm_ok = bool(out and out[0].outputs[0].text is not None)
        del llm
    except Exception as e:  # noqa: BLE001
        vllm_err = f"{type(e).__name__}: {e}"[:500]

    return {"trait": trait, "neutral": neutral, "n_adapter_modules": len(mods),
            "n_ckpt_tensors": len(ckpt_names),
            "n_mapped": sum(v is not None for v in mapping.values()),
            "unmapped": unmapped[:20],
            "sample_mapping": dict(list(mapping.items())[:5]),
            "vllm_ok": vllm_ok, "vllm_version": vllm_version,
            "vllm_err": vllm_err}


