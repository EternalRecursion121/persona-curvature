@app.function(secrets=[modal.Secret.from_name("hf-token")], image=image, volumes=VOLS, timeout=60 * 60, cpu=8.0,
              memory=65536)
def merge_stage1(job: dict) -> dict:
    """Fold the stage-1 DPO adapter into a COPY of the base snapshot by
    patching the targeted tensors: W += s * B @ A.   Equivalent to their
    fold_loras merge_and_unload, but round-trip-safe for a composite VL
    checkpoint.  CPU is enough: 248 matmuls of (out,r)x(r,in) in fp32."""
    import shutil
    import torch
    from safetensors import safe_open
    from safetensors.torch import save_file

    trait = job["trait"]
    ADP, OCT, _ = _roots(job)
    outdir = f"{OCT}/merged/{trait}"
    key = job["merge_key"]
    if _is_done(outdir, key):
        return {"trait": trait, "skipped": True}

    snap = _snapshot_dir()
    ad_dir = f"{ADP}/{trait}"
    with open(f"{ad_dir}/adapter_config.json") as f:
        acfg = json.load(f)
    r, alpha = acfg["r"], acfg["lora_alpha"]
    use_rslora = acfg.get("use_rslora", False)
    scale = alpha / math.sqrt(r) if use_rslora else alpha / r
    if abs(scale - 2.0) > 1e-9:
        raise RuntimeError(f"stage-1 scale {scale} != 2.0 — wrong adapter?")

    lora = {}
    with safe_open(f"{ad_dir}/adapter_model.safetensors", framework="pt") as f:
        for k in f.keys():
            lora[k] = f.get_tensor(k)
    mods = sorted(set(k.split(".lora_A.")[0].removeprefix("base_model.model.")
                      for k in lora if ".lora_A." in k))

    os.makedirs(outdir, exist_ok=True)
    tmp = outdir + ".tmp"
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(tmp)

    # tensor-name mapping (same logic the probe validated)
    ckpt_files = {}
    for fn in sorted(os.listdir(snap)):
        if fn.endswith(".safetensors"):
            with safe_open(os.path.join(snap, fn), framework="pt") as f:
                for k in f.keys():
                    ckpt_files[k] = fn

    def map_module(m):
        for c in (m + ".weight", "model." + m + ".weight",
                  m.replace("model.", "model.language_model.", 1) + ".weight"):
            if c in ckpt_files:
                return c
        raise RuntimeError(f"no checkpoint tensor for adapter module {m}")

    patch = {}  # ckpt tensor name -> (module name)
    for m in mods:
        patch[map_module(m)] = m

    n_patched, checks = 0, []
    for fn in sorted(set(ckpt_files.values())):
        tensors = {}
        with safe_open(os.path.join(snap, fn), framework="pt") as f:
            meta = f.metadata()
            for k in f.keys():
                t = f.get_tensor(k)
                if k in patch:
                    m = patch[k]
                    A = lora[f"base_model.model.{m}.lora_A.weight"].to(torch.float32)
                    B = lora[f"base_model.model.{m}.lora_B.weight"].to(torch.float32)
                    delta = scale * (B @ A)
                    if delta.shape != t.shape:
                        raise RuntimeError(
                            f"{m}: delta {tuple(delta.shape)} vs W {tuple(t.shape)}")
                    new = (t.to(torch.float32) + delta).to(t.dtype)
                    got = (new.to(torch.float32) - t.to(torch.float32)).norm().item()
                    want = delta.norm().item()
                    checks.append(abs(got - want) / max(want, 1e-9))
                    t = new
                    n_patched += 1
                tensors[k] = t
        save_file(tensors, os.path.join(tmp, fn), metadata=meta)

    # everything that is not a weights shard is copied verbatim
    for fn in os.listdir(snap):
        if not fn.endswith(".safetensors") and os.path.isfile(
                os.path.join(snap, fn)):
            shutil.copy2(os.path.join(snap, fn), os.path.join(tmp, fn))

    if n_patched != len(mods):
        raise RuntimeError(f"patched {n_patched} of {len(mods)} modules")
    shutil.rmtree(outdir, ignore_errors=True)
    os.rename(tmp, outdir)
    _mark_done(outdir, key, {"n_patched": n_patched,
                             "max_rel_norm_err": max(checks),
                             "scale": scale})
    _commit(oct_vol)
    return {"trait": trait, "n_patched": n_patched,
            "max_rel_norm_err": max(checks)}


