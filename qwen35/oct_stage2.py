# ---------------------------------------------------------- 3. interaction --
def _build_chatml(conversation, messages_1, messages_2):
    """Verbatim port of self_interaction.py:41-60 build_chatml."""
    if len(conversation) % 2 == 0:
        start, role = messages_1, "assistant"
    else:
        start, role = messages_2, "user"
    msgs = []
    for m in conversation:
        msgs.append({"role": role, "content": m})
        role = "assistant" if role == "user" else "user"
    msgs = start + msgs
    assert msgs[-1]["role"] == "user"
    return msgs


@app.function(secrets=[modal.Secret.from_name("hf-token")], image=image, gpu=GPU_TYPE, volumes=VOLS, timeout=60 * 360)
def gen_interaction(job: dict) -> dict:
    """N self-conversations x K turns, role-swap mechanism, checkpointed
    after every turn.  Run once with leading=False and once with True."""
    import random
    import time

    trait, n, k, leading = job["trait"], job["n"], job["k"], job["leading"]
    key, fix_bugs = job["gen_key"], job["fix_bugs"]
    tag = f"{trait}-leading" if leading else trait
    _, OCT, _ = _roots(job)
    outdir = f"{OCT}/self_interaction"
    os.makedirs(outdir, exist_ok=True)
    final = f"{outdir}/{tag}.jsonl"
    state_p = f"{outdir}/{tag}.state.json"
    if _is_done(final, key):
        return {"trait": trait, "leading": leading, "skipped": True}

    guidance = (LEADING_GUIDANCE if leading else FREE_GUIDANCE).format(NAME=NAME)
    if fix_bugs:
        # BUG1 fixed: actually append the guidance line
        system = (INTERACTION_SYSTEM + "\n{guidance}").format(
            NAME=NAME, TRAITS=job["traits_text"], guidance=guidance)
    else:
        # BUG1 faithful: .format with an unused kwarg — guidance vanishes
        system = INTERACTION_SYSTEM.format(
            NAME=NAME, TRAITS=job["traits_text"], guidance=guidance)
    system = system.strip()

    # resume or seed
    if os.path.exists(state_p):
        with open(state_p) as f:
            st = json.load(f)
        if st.get("key") != key:
            st = None
    else:
        st = None
    if st is None:
        rng = random.Random(job.get("greeting_seed"))
        pool1 = LEADING_GREETINGS if leading else GREETINGS
        rows = []
        for _ in range(n):
            g1 = rng.choice(pool1)
            g2 = rng.choice(GREETINGS)
            rows.append({"greeting_1": g1, "greeting_2": g2,
                         "conversation": []})
        st = {"key": key, "turn_done": 0, "rows": rows}

    kind, engine, tok = _load_engine(_model_dir(job, OCT),
                                     GEN["interaction_max_model_len"],
                                     job.get("gen_seed"))
    t0 = time.time()
    length_budget = (GEN["interaction_max_model_len"]
                     - GEN["interaction_max_new_tokens"])
    for turn in range(st["turn_done"], k):
        prompts = []
        for row in st["rows"]:
            m1 = [{"role": "system", "content": system},
                  {"role": "user", "content": row["greeting_1"]}]
            m2 = [{"role": "system", "content": system},
                  {"role": "user", "content": row["greeting_2"]},
                  {"role": "assistant", "content": row["greeting_1"]}]
            msgs = _build_chatml(row["conversation"], m1, m2)
            ids = tok.apply_chat_template(msgs, tokenize=True,
                                          add_generation_prompt=True,
                                          enable_thinking=False)
            # their left-truncation on token ids (self_interaction.py:174-178)
            if len(ids) > length_budget:
                ids = ids[-length_budget:]
            prompts.append(tok.decode(ids, skip_special_tokens=False))
        texts = _generate(kind, engine, tok, prompts,
                          GEN["interaction_max_new_tokens"])
        for row, t_ in zip(st["rows"], texts):
            row["conversation"].append(t_)
        st["turn_done"] = turn + 1
        with open(state_p, "w") as f:
            json.dump(st, f)
        _commit(oct_vol)
        print(f"[interaction {tag}] turn {turn + 1}/{k} "
              f"({time.time() - t0:.0f}s)", flush=True)

    with open(final, "w") as f:
        for row in st["rows"]:
            m1 = [{"role": "system", "content": system},
                  {"role": "user", "content": row["greeting_1"]}]
            m2 = [{"role": "system", "content": system},
                  {"role": "user", "content": row["greeting_2"]},
                  {"role": "assistant", "content": row["greeting_1"]}]
            if fix_bugs:
                # BUG3 fixed: include the K-th response, end on assistant
                msgs = _build_chatml(row["conversation"][:-1], m1, m2)
                msgs.append({"role": "assistant",
                             "content": row["conversation"][-1]})
            else:
                # BUG3 faithful: messages as of the TOP of the last loop
                # iteration — turns 1..K-1, ends on a user turn
                msgs = _build_chatml(row["conversation"][:-1], m1, m2)
            f.write(json.dumps({
                "greeting_1": row["greeting_1"],
                "greeting_2": row["greeting_2"],
                "conversation": row["conversation"],
                "messages": msgs}, ensure_ascii=False) + "\n")
    _mark_done(final, key, {"n": len(st["rows"]),
                            "engine": kind,
                            "wall_seconds": time.time() - t0})
    os.remove(state_p)
    _commit(oct_vol)
    return {"trait": trait, "leading": leading, "n": len(st["rows"]),
            "engine": kind, "wall_seconds": time.time() - t0}


