"""OCT STAGE 2 (introspection) on Modal — phase 10 of the qwen35 plan.

Open Character Training's second stage, run as faithfully as possible to their
released code (vendor/OpenCharacterTraining, MIT), on our 134 single-trait
stage-1 DPO adapters instead of their 11 hand-written personas.

WHAT THEIR CODE ACTUALLY DOES (mapped from the repo, not the paper):

  1. SELF-REFLECTION   character/introspection/self_reflection.py
     10 fixed introspective instructions x N=1000 samples, generated by the
     post-DPO model (base + stage-1 LoRA) under the App-A system prompt with
     the "reflective mood" line.  System prompt DROPPED from training rows.
  2. SELF-INTERACTION  character/introspection/self_interaction.py
     N=1000 conversations x K=10 turns, run TWICE (--leading and free), the
     model talking to a copy of itself via role-swapped re-rendering.
  3. ASSEMBLY          character/introspection/data.py
     reflections + both interaction runs -> one sft_data/<persona>.jsonl,
     interaction rows get a "simplified" system prompt, shuffled.
  4. SFT               finetuning/introspection/qwen.sh -> openrlhf train_sft
     rank 64 alpha 128 all-linear LoRA on the DPO-MERGED base, lr 5e-5,
     batch 32 (2 micro x accum), 1 epoch, max_len 3072, warmup 0.1,
     betas (0.9, 0.98), grad clip 1.0, seed 123456, bf16, loss on the final
     segment only (--multiturn is NOT passed).
  5. RELEASE MERGE     tools/merge_loras.py
     add_weighted_adapter(["dpo","sft"], [1.0, 0.25], combination_type="linear")

FAITHFUL-BUG POLICY.  Their released code has five discrepancies against the
paper (mapped 2026-08-22; the writeup documents each).  Following this
project's precedent (sq_approx_kl: reproduce the code, not the prose), the
default is BUG-FAITHFUL; --fix-oct-bugs flips all of them at once:

  BUG1  the free/leading "guidance" sentence is formatted into a template
        with no {guidance} placeholder, so it NEVER reaches the model.  The
        only leading-vs-free difference is the greeting pool.
  BUG2  the training-time "simplified" system prompt is never .format()ed:
        the literal characters {NAME} appear in the training data.
  BUG3  the interaction "messages" column is only rebuilt at the TOP of the
        turn loop, so the saved row holds turns 1..K-1, ends on a USER turn,
        and the SFT slice trains on a header-misaligned, 5-char-truncated
        user utterance.
  BUG4  (a consequence, not reproduced separately) max_len 3072 silently
        drops most interaction rows at the SFT tokenizer.  We COUNT and
        record the drop instead of preventing it.
  BUG5  merge_loras.py reads {family}-test/ for the SFT adapter; we use our
        real path (this one cannot be reproduced meaningfully).

DELIBERATE DEVIATIONS, each recorded in runmeta:
  - persona = one TRAIT; {TRAITS} in the App-A template is filled with the
    trait's constitution document verbatim (the document that conditioned all
    stage-1 data), not a numbered assertion list — we have no assertion lists.
  - enable_thinking=False on every apply_chat_template.  OCT never met a
    thinking template; Qwen3.5's opens a reasoning block that (a) leaks
    <think> into generations and (b) breaks the prompt-prefix slice the SFT
    step depends on.  Same rule stage 1 used (HANDOVER trap 4).
  - the DPO merge is applied by PATCHING the base snapshot's safetensors in a
    copy of the snapshot directory (W += s·B@A on the 248 targeted tensors),
    not merge_and_unload + re-save: Qwen3.5-4B is a composite VL checkpoint
    and a causal-LM re-save is not guaranteed to round-trip.  The patch is
    mathematically identical to their fold_loras and keeps every other byte
    of the snapshot intact.  Verified per tensor: ||W_new - W_old|| matches
    s·||B@A|| to bf16 precision.
  - SFT runs on transformers Trainer with hand-built labels reproducing
    OpenRLHF's exact row semantics (prompt = render(messages[:-1], gen
    prompt) / response = char-offset slice; right pad; drop row if
    prompt_len >= max_len-2; append " "+eos if missing; force last token to
    eos; labels only on the response span) — the same reimplementation
    strategy stage 1 used for their DPO fork, validated there to 4dp.
  - generation engine is vLLM if it can load the merged snapshot, else
    transformers generate (recorded which; smoke decides).

CHECKPOINTS (Samuel: "save checkpoints at every step").  Volume layout, all
under the phase-10 volume, resumable at every stage:
    /oct/merged/<trait>/                 patched base snapshot (skip if done)
    /oct/self_reflection/<trait>.p<i>.jsonl   one shard per instruction i
    /oct/self_interaction/<trait>[-leading].state.json   after EVERY turn
    /oct/self_interaction/<trait>[-leading].jsonl        final
    /oct/sft_data/<trait>.jsonl + <trait>.diagnostics.json
    /oct/loras_introspection/<trait>/    adapter + checkpoint-*/ + runmeta.json
    /oct/personas/<trait>/               final weighted merge
Every stage writes a DONE marker (<path>.done.json with sha + counts) and
skips itself when the marker matches, so re-running the driver resumes.

usage (local entrypoint):
    PC_PHASE_BUDGET=80 modal run oct_stage2.py --traits extraverted --probe-only
    PC_PHASE_BUDGET=80 modal run oct_stage2.py --traits extraverted \
        --n-reflection 40 --n-interaction 8 --k-turns 4     # tiny smoke
    PC_PHASE_BUDGET=80 modal run oct_stage2.py --traits extraverted,warm,organized
"""

