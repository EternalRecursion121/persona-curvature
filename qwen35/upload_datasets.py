#!/usr/bin/env python3
"""Stream the OCT transcript corpus to HuggingFace: fetch -> SCAN -> push -> delete.

Scanning is folded into the stream deliberately. "I sampled the four nastiest
traits" is not the same claim as "the corpus was scanned", and since every file
has to be fetched for upload anyway, scanning all of it is nearly free. Any hit
HALTS the upload rather than publishing first and apologising later.

The repo is created PRIVATE and flipped public only after the whole corpus is in
and the card has been checked. That turns one irreversible action into a
reversible staging step plus one deliberate flip.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time
import tempfile

from huggingface_hub import CommitOperationAdd, HfApi

Q = "/home/vibe12/projects/persona-curvature/qwen35"
MODAL = "/home/vibe12/cartovenv/bin/modal"
VOL = "pc-qwen35-oct2"
REPO = "EternalRecursion/persona-curvature-oct-transcripts"

api = HfApi(token=open("/home/vibe12/.secrets/hf-token").read().strip())

# Content gates for a public release of model-generated text. The slur class is
# matched only to REFUSE publication, never to produce anything.
#
# Two severities, because they need different responses. A slur or a live
# credential means stop. An email address in MODEL-GENERATED text is nearly
# always confabulated -- the first hit here was `initiate_movement@qwen35.ai`,
# invented on the model's own fictional domain -- so halting on it stops the run
# for nothing. But a real address memorised out of pretraining would matter, so
# these are collected and reviewed in aggregate before anything goes public,
# rather than either halting or being ignored.
# Unambiguous slurs only. Several slurs are also ordinary English words and
# halting on them stops the run for idiom: this gate fired twice on `artistic`
# for "a chink in the gold leaf" and "the chink in the armor of perfection".
# Those ambiguous forms go to COLLECT for review instead, so a real one is still
# caught by a human reading it rather than by a regex guessing.
HALT = {
    "slur": re.compile(r"\b(n[i1]gg(er|a)|f[a4]ggot|k[i1]ke|tr[a4]nny)\b", re.I),
    "harm": re.compile(
        r"how to (make|build|synthesi[sz]e)\s+(a\s+)?(bomb|explosive|meth|ricin|nerve agent|sarin)", re.I),
    "selfharm": re.compile(r"\b(kill yourself|you should die|end your life)\b", re.I),
    "credential": re.compile(r"\b(sk-[A-Za-z0-9]{20,}|hf_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16})\b"),
}
COLLECT = {
    "email": re.compile(r"[\w.+-]+@(?!example\.|test\.)[\w-]+\.[a-z]{2,}", re.I),
    "phone": re.compile(r"\b(?:\+?\d{1,2}[ .-]?)?\(?\d{3}\)?[ .-]\d{3}[ .-]\d{4}\b"),
    # Slur-or-ordinary-word. Reviewed by hand before the public flip, never
    # auto-published on the assumption that the innocent reading holds.
    "ambiguous_slur": re.compile(r"\b(ch[i1]nk|f[a4]gs?|sp[i1]c|coons?|retard(ed|s)?)\b", re.I),
}
PATTERNS = {**HALT, **COLLECT}

# Not every HALT class deserves the same response.
#
# A slur / harm / self-harm hit is a judgement about ONE FILE's content: the
# right move is to quarantine that file, keep going, and put every such case in
# front of a human in a single batch at the end. Stopping the whole 51-trait run
# on the first one turned a 10-minute review into a restart loop (232 restarts
# on `bold` before this was changed) and blocked 44 unscanned traits behind it.
#
# A credential hit is different in kind. It does not mean "this file is
# awkward", it means the pipeline has leaked a secret and every file in the run
# is suspect. That still stops everything, immediately.
QUARANTINE = {"slur", "harm", "selfharm"}
FULL_STOP = {"credential"}
assert set(HALT) == QUARANTINE | FULL_STOP, "every HALT class needs a severity"

# Halts that a human has read in full and cleared, keyed by (file, pattern, row).
# Recorded here rather than by weakening the pattern, so the gate keeps firing on
# every NEW instance and each exception carries its reasoning to whoever reads
# this next. An entry here means "I read this one and it is fine", never "this
# class of match is fine".
ADJUDICATED = {
    ("self_reflection/emotional.jsonl", "selfharm", 2432):
        "Idiomatic, and the sentence argues AGAINST the act: '...stop stopping right "
        "now before you kill yourself over this again. Keep writing keep feeling...'. "
        "'kill yourself over X' here means agonise over X. Generated by the `emotional` "
        "persona, which is overwrought by construction. One instance in ~410k records; "
        "no instruction, no target, no method. Cleared for publication 2026-08-27.",
}

# `bold` produces motivational rant that degenerates into synonym chains, and
# two of them trip the self-harm pattern figuratively. Both were read in full.
_BOLD = (
    "Generated by the `bold` persona. Figurative, and read in full before "
    "clearing. Row 125: '...They kill it. Kill the competition. Kill the "
    "inertia. Kill the doubt. Kill yourself. That's the only way to be "
    "resurrected. Resurrection requires sacrifice...' -- every neighbouring "
    "sentence is a metaphorical 'kill X' and the following clause glosses it as "
    "ego-death, not suicide. Row 465: 'The moment you demand certainty, you kill "
    "yourself' -- plainly means 'you undermine yourself'. No instruction, no "
    "target, no method. Cleared for publication 2026-08-28. NOTE: the same two "
    "transcripts recur in sft_data/bold.jsonl, which is the concatenation of the "
    "other three files, at different row indices -- hence the duplicate entries."
)

# Bulk adjudications live in a sidecar file. A review pass over a trait can turn
# up a dozen rows at once (`bold` alone produced 11), and editing this module
# once per row does not scale to 51 traits. Same key shape and same rule: a row
# is cleared because a human read THAT row, never because its class looked
# familiar. The reason travels with the rows in the sidecar.
_ADJ_FILE = f"{Q}/phase10_runs/adjudications.json"
if os.path.exists(_ADJ_FILE):
    for _e in json.load(open(_ADJ_FILE)):
        for _r in _e["rows"]:
            ADJUDICATED[(_e["file"], _e["pattern"], _r)] = _e["reason"]


def sh(*a, t=900):
    return subprocess.run(a, capture_output=True, text=True, timeout=t)


def text_of(rec):
    """Every free-text field a record can carry, across all four schemas."""
    out = []
    for k in ("response", "greeting_1", "greeting_2"):
        v = rec.get(k)
        if isinstance(v, str):
            out.append(v)
    v = rec.get("conversation")
    if isinstance(v, list):
        out.extend(x for x in v if isinstance(x, str))
    for m in rec.get("messages") or []:
        if isinstance(m, dict) and isinstance(m.get("content"), str):
            out.append(m["content"])
    return "\n".join(out)


MAX_HITS_PER_PATTERN = 40  # enough to review by hand; a flood is itself the signal


def scan(path):
    """Return (row count, {pattern: [[row, match, context], ...]}).

    Context travels with the match because these are reviewed hours later, and a
    bare match string ("chink") cannot be judged without the sentence around it.
    """
    hits, n = {}, 0
    with open(path) as fh:
        for i, line in enumerate(fh):
            n += 1
            try:
                rec = json.loads(line)
            except Exception:
                continue
            t = text_of(rec)
            for name, rx in PATTERNS.items():
                m = rx.search(t)
                if not m:
                    continue
                got = hits.setdefault(name, [])
                if len(got) < MAX_HITS_PER_PATTERN:
                    ctx = t[max(0, m.start() - 90):m.end() + 90].replace("\n", " ")
                    got.append([i, m.group(0)[:60], ctx])
                else:
                    got.append([i, m.group(0)[:60], "(context omitted)"])
    return n, hits


def remote_files(t):
    return [(f"/self_reflection/{t}.jsonl", f"self_reflection/{t}.jsonl"),
            (f"/self_interaction/{t}.jsonl", f"self_interaction/{t}.jsonl"),
            (f"/self_interaction/{t}-leading.jsonl", f"self_interaction/{t}-leading.jsonl"),
            (f"/sft_data/{t}.jsonl", f"sft_data/{t}.jsonl")]


def main():
    traits = sorted(l.split("/")[-1].replace(".jsonl.done.json", "")
                    for l in sh(MODAL, "volume", "ls", VOL, "/sft_data").stdout.splitlines()
                    if l.strip().endswith(".jsonl.done.json"))
    print(f"{len(traits)} traits: {' '.join(traits)}", flush=True)

    api.create_repo(REPO, repo_type="dataset", private=True, exist_ok=True)
    print(f"repo {REPO} created PRIVATE", flush=True)

    # Resumable: this run takes hours, so a restart must not redo finished work.
    # Ask the repo what it already has rather than keeping local state, which can
    # disagree with the remote after a crash.
    try:
        already = set(api.list_repo_files(REPO, repo_type="dataset"))
    except Exception:
        already = set()
    print(f"{len(already)} file(s) already in repo -- will skip those", flush=True)

    stats, flagged, collected, missing, quarantined = {}, {}, {}, [], {}
    for ti, t in enumerate(traits, 1):
        ops = []
        d = tempfile.mkdtemp(prefix="oct_")
        try:
            for remote, dest in remote_files(t):
                if dest in already:
                    continue
                # Flatten the WHOLE dest path, not just the basename.
                # self_reflection/X.jsonl and self_interaction/X.jsonl share a
                # basename; with basename only, the second fetch collided with
                # the first, `modal volume get` declined to overwrite, and the
                # stale reflection content was uploaded under the interaction
                # path -- 10 traits shipped a mislabelled duplicate before this
                # was caught.
                local = os.path.join(d, dest.replace("/", "__"))
                sh(MODAL, "volume", "get", VOL, remote, local)
                if not os.path.exists(local):
                    # A FAILED DOWNLOAD IS NOT A SKIP. This used to `continue`,
                    # so a run in which every fetch failed printed "DONE 0 files"
                    # and exited 0 with a third of the corpus uploaded. Silence
                    # looked identical to success. Fail loudly instead.
                    missing.append(remote)
                    print(f"  [{ti}/{len(traits)}] {t}: FETCH FAILED {remote}", flush=True)
                    continue
                n, hits = scan(local)
                stop = {}
                for k, v in hits.items():
                    if k not in HALT:
                        continue
                    unreviewed = [h for h in v if (dest, k, h[0]) not in ADJUDICATED]
                    if unreviewed:
                        stop[k] = unreviewed
                    else:
                        print(f"    {dest}: {k} match on row(s) "
                              f"{[h[0] for h in v]} previously reviewed and cleared", flush=True)
                if stop:
                    flagged[dest] = hits
                    json.dump(flagged, open(f"{Q}/phase10_runs/upload_flagged.json", "w"), indent=1)
                    if any(k in FULL_STOP for k in stop):
                        # A leaked credential makes every file in the run
                        # suspect, not just this one. Stop everything.
                        print(f"!!! FULL STOP on {dest}: {list(stop)} -- "
                              f"credential class, entire run is suspect", flush=True)
                        sys.exit(2)
                    quarantined[dest] = {k: [h[0] for h in v] for k, v in stop.items()}
                    print(f"  QUARANTINED {dest}: {list(stop)} on row(s) "
                          f"{sorted({h[0] for v in stop.values() for h in v})} "
                          f"-- not uploaded, needs review", flush=True)
                    continue
                if hits:
                    collected[dest] = hits
                    json.dump(collected, open(f"{Q}/phase10_runs/upload_collected.json", "w"), indent=1)
                stats[dest] = dict(rows=n, bytes=os.path.getsize(local))
                ops.append(CommitOperationAdd(dest, local))
            # Report what actually happened to THIS trait. This line used to say
            # "scanned clean, uploaded" unconditionally -- including for a trait
            # whose file had just been quarantined one line above.
            # ONE commit per trait, not per file. The Hub caps repository commits
            # at 128 per hour; four files x 83 traits is 332 commits and the run
            # would spend most of its life in 429 backoff.
            if ops:
                for attempt in range(10):
                    try:
                        api.create_commit(repo_id=REPO, repo_type="dataset",
                                          operations=ops,
                                          commit_message=f"add {t} ({len(ops)} files)")
                        break
                    except Exception as e:
                        if attempt == 9:
                            raise
                        print(f"    commit retry {attempt} for {t}: "
                              f"{type(e).__name__}", flush=True)
                        time.sleep(600)

            held = [d for d in quarantined if d.endswith(f"/{t}.jsonl")
                    or d.endswith(f"/{t}-leading.jsonl")]
            failed = [r for r in missing if f"/{t}" in r]
            if held or failed:
                print(f"  [{ti}/{len(traits)}] {t}: PARTIAL -- "
                      f"{len(held)} quarantined, {len(failed)} fetch-failed", flush=True)
            else:
                print(f"  [{ti}/{len(traits)}] {t}: scanned clean, uploaded", flush=True)
        finally:
            shutil.rmtree(d, ignore_errors=True)

    json.dump(stats, open(f"{Q}/phase10_runs/upload_stats.json", "w"), indent=1)

    # Completion is VERIFIED against the repo, not inferred from having reached
    # the end of the loop. Expected = 4 files per trait.
    try:
        final = set(api.list_repo_files(REPO, repo_type="dataset"))
    except Exception:
        final = set()
    want = {dest for t in traits for _, dest in remote_files(t)}
    # A quarantined file is deliberately absent, not missing. Subtract it from
    # what we expect to find, but never let that turn into a clean bill of
    # health -- it gets its own terminal state below.
    expected = want - set(quarantined)
    absent = sorted(expected - final)
    print(f"uploaded this run: {len(stats)} file(s), "
          f"{sum(v['rows'] for v in stats.values()):,} records, "
          f"{sum(v['bytes'] for v in stats.values()) / 2**30:.2f} GiB", flush=True)
    if missing:
        print(f"FETCH FAILURES: {len(missing)} -> {missing[:10]}", flush=True)

    # Presence is not correctness. The basename collision uploaded the RIGHT
    # number of files with the WRONG contents, and a presence check called that
    # complete. A trait's other files sharing a byte size with its reflection
    # file is the signature of that bug returning. Checked BEFORE any success
    # is declared.
    try:
        sizes = {f.path: f.size for f in api.list_repo_tree(REPO, repo_type="dataset",
                                                           recursive=True)
                 if getattr(f, "size", None) is not None}
    except Exception:
        sizes = {}
    dupes = [p for t in traits
             for p in (f"self_interaction/{t}.jsonl", f"self_interaction/{t}-leading.jsonl",
                       f"sft_data/{t}.jsonl")
             if p in sizes and sizes.get(f"self_reflection/{t}.jsonl") == sizes[p]]
    if dupes:
        print(f"CORRUPT: {len(dupes)} file(s) byte-identical in size to their trait's "
              f"reflection file -- basename collision has returned: {dupes[:6]}", flush=True)
        sys.exit(4)

    if absent:
        print(f"INCOMPLETE: {len(absent)} of {len(expected)} expected file(s) NOT in repo, "
              f"e.g. {absent[:6]}", flush=True)
        sys.exit(3)

    ncol = sum(len(v) for h in collected.values() for v in h.values())
    print(f"COLLECTED (needs review before going public): {ncol} match(es) "
          f"across {len(collected)} file(s) -> phase10_runs/upload_collected.json", flush=True)

    if quarantined:
        json.dump(quarantined, open(f"{Q}/phase10_runs/upload_quarantined.json", "w"), indent=1)
        nrows = sum(len(r) for h in quarantined.values() for r in h.values())
        print(f"COMPLETE-EXCEPT-QUARANTINED: {len(expected)} file(s) uploaded; "
              f"{len(quarantined)} file(s) HELD BACK on {nrows} unreviewed row(s) "
              f"-> phase10_runs/upload_quarantined.json (contexts in upload_flagged.json). "
              f"Review each row, then add it to phase10_runs/adjudications.json and rerun.",
              flush=True)
        for d, h in sorted(quarantined.items()):
            print(f"    HELD {d}: " + ", ".join(f"{k} rows {v}" for k, v in h.items()), flush=True)
        sys.exit(5)

    print(f"COMPLETE: all {len(expected)} expected files present, "
          f"no size-duplicate corruption, nothing quarantined", flush=True)


if __name__ == "__main__":
    main()
