/* The loadings panel and the neighbour explorer.  The factor chart itself moved
   to assets/map3d.js in the v2 redesign, where it is drawn in three dimensions on
   a canvas instead of two on an SVG; what is left here are the two panels beside
   it, which are bars and tables and were never scatters.
   Vanilla; no library. Data comes from /data/chart.json and /data/neighbours.json,
   both generated by companion/build_companion.py. */
(function () {
  "use strict";

  var BASE = (document.querySelector('link[href$="assets/site.css"]').getAttribute('href') || '')
    .replace(/assets\/site\.css$/, '');
  var FC = ['var(--f0)', 'var(--f1)', 'var(--f2)', 'var(--f3)', 'var(--f4)'];
  var SVGNS = 'http://www.w3.org/2000/svg';

  function el(name, attrs) {
    var n = document.createElementNS(SVGNS, name);
    for (var k in attrs) if (attrs[k] !== null && attrs[k] !== undefined) n.setAttribute(k, attrs[k]);
    return n;
  }
  function get(url) { return fetch(BASE + url).then(function (r) { return r.json(); }); }
  function debounce(fn, ms) { var t; return function () { clearTimeout(t); t = setTimeout(fn, ms); }; }

  var DATA = null;

  /* --------------------------------------------------------------- loadings */
  function Loadings(host) {
    var sel = document.getElementById('load-factor');
    DATA.factors.forEach(function (f, i) {
      var o = document.createElement('option'); o.value = i; o.textContent = f.title; sel.appendChild(o);
    });
    sel.addEventListener('change', function () { draw(+sel.value); });
    draw(0);
    window.addEventListener('resize', debounce(function () { draw(+sel.value); }, 200));

    function draw(fi) {
      var zoo = DATA.rows.filter(function (r) { return r.l; });
      var sorted = zoo.slice().sort(function (a, b) { return b.l[fi] - a.l[fi]; });
      var pos = sorted.slice(0, 14);
      var neg = sorted.slice(-14).reverse();
      var maxv = Math.max.apply(null, zoo.map(function (r) { return Math.abs(r.l[fi]); }));
      var W = Math.max(300, Math.round(host.getBoundingClientRect().width) || 900);
      var oneCol = W < 620;
      var rowh = 20, H = (oneCol ? 28 * rowh + 76 : 14 * rowh + 54);
      var svg = el('svg', { viewBox: '0 0 ' + W + ' ' + H, role: 'img' });
      svg.setAttribute('aria-label', 'highest and lowest loading trait words on ' + DATA.factors[fi].title);
      var colw = oneCol ? W : W / 2;
      var barmax = colw - 24 - 132 - 54;
      var groups = oneCol
        ? [[pos, 1, 12, 0], [neg, -1, 12, 14 * rowh + 40]]
        : [[pos, 1, 16, 0], [neg, -1, colw + 16, 0]];
      groups.forEach(function (grp) {
        var list = grp[0], sign = grp[1], x0 = grp[2], y0 = grp[3];
        var head = el('text', { x: x0, y: y0 + 16, class: 'axis' });
        head.textContent = sign > 0 ? 'highest positive loadings' : 'highest negative loadings';
        svg.appendChild(head);
        list.forEach(function (r, i) {
          var y = y0 + 36 + i * rowh;
          var w = Math.abs(r.l[fi]) / maxv * barmax;
          var bx = x0 + 132;
          svg.appendChild(el('rect', { x: bx, y: y - 8, width: Math.max(1, w), height: 11, fill: FC[fi], 'fill-opacity': 0.85 }));
          var lab = el('text', { x: x0 + 126, y: y, class: 'axis', 'text-anchor': 'end' });
          lab.setAttribute('fill', 'var(--ink)'); lab.setAttribute('font-size', '11.5');
          lab.textContent = r.t; svg.appendChild(lab);
          var num = el('text', { x: bx + w + 5, y: y, class: 'axis' });
          num.textContent = (r.l[fi] >= 0 ? '+' : '−') + Math.abs(r.l[fi]).toFixed(3);
          svg.appendChild(num);
        });
      });
      host.innerHTML = '';
      host.appendChild(svg);
      var cap = document.getElementById('load-caption');
      if (cap) {
        cap.textContent = 'Oblimin pattern loadings, centred k = 5 solution. Sum of squared ' +
          'loadings ' + DATA.factors[fi].ss.toFixed(2) + '; closest Goldberg factor ' +
          DATA.factors[fi].b5 + ' at Tucker phi ' + DATA.factors[fi].phi.toFixed(3) + '.';
      }
      var link = document.getElementById('load-wiki');
      if (link) { link.href = link.dataset.base + DATA.factors[fi].wiki + '.html';
                  link.textContent = 'The ' + DATA.factors[fi].title + ' factor on the wiki'; }
    }
  }

  /* ------------------------------------------------------------- neighbours */
  function Neighbours(host, NB) {
    var pick = document.getElementById('nb-trait');
    var names = NB.names.slice().sort();
    names.forEach(function (n) {
      var o = document.createElement('option'); o.value = n; o.textContent = n; pick.appendChild(o);
    });
    pick.value = 'warm';
    pick.addEventListener('change', function () { draw(pick.value); });
    draw('warm');

    function draw(slug) {
      var cols = ['stage1', 'stage2', 'persona'];
      var titles = { stage1: 'Stage one (DPO)', stage2: 'Stage two (introspection SFT)', persona: 'Persona (the deployed merge)' };
      var out = '';
      cols.forEach(function (c) {
        var d = NB.grams[c][slug];
        if (!d) return;
        var near = d.near.slice(0, 8).map(function (p) { return row(p, true); }).join('');
        var far = d.far.slice(0, 4).map(function (p) { return row(p, false); }).join('');
        out += '<div style="padding:0.9rem 1rem"><h4 style="margin-top:0">' + titles[c] + '</h4>' +
          '<table style="font-size:0.84rem"><tbody>' + near +
          '<tr><td colspan="2" style="color:var(--faint);font-family:var(--mono);font-size:0.66rem;' +
          'letter-spacing:0.08em;text-transform:uppercase;padding-top:0.7rem">farthest</td></tr>' +
          far + '</tbody></table>' +
          '<p class="small" style="color:var(--muted);margin:0.6rem 0 0">mean cosine to the other 133: ' +
          '<span class="num">' + d.mean.toFixed(4) + '</span></p></div>';
      });
      host.innerHTML = out;
    }
    function row(p, near) {
      return '<tr><td><a href="' + BASE + 'traits/' + p[0] + '.html">' + p[0] + '</a></td>' +
        '<td class="n">' + (p[1] >= 0 ? '+' : '−') + Math.abs(p[1]).toFixed(3) + '</td></tr>';
    }
  }

  /* -------------------------------------------------------------------- go */
  document.addEventListener('DOMContentLoaded', function () {
    var loadhost = document.getElementById('loadings');
    var nbhost = document.getElementById('neighbours');
    if (!loadhost && !nbhost) return;
    get('data/chart.json').then(function (d) {
      DATA = d;
      if (loadhost) Loadings(loadhost);
      if (nbhost) get('data/neighbours.json').then(function (nb) { Neighbours(nbhost, nb); });
    }).catch(function (e) {
      if (loadhost) loadhost.innerHTML = '<p class="caveat">The chart data did not load: ' + e + '</p>';
    });
  });
})();
